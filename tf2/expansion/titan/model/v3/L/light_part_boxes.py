"""Grounding / test boxes for Unity's TitanDimsLight.Parts, from the light meshes (light clips, after the heavy's part_boxes.py, H5).

  blender.exe -b -P light_part_boxes.py -- L1 4 <out.cs.txt>

Each part's local bounds (zero pose; a part's origin is its joint) become a box on the animation bone that moves it in Unity: Unity's TitanBone has
no right wrist, right fingers, weapon, wings, hatch or optic, so those parts ride their nearest driven parent (right hand and weapon on ElbowR: the
animator never turns the light's right wrist; wings, hatch, optic, launcher stand-in on Torso). The box centre is given from that bone's joint.
Not shrunk (Lowest grounds clip poses with them). Lowest only looks at boxes named foot* / shin* unless asked for all: parts on the ankle bones are
named foot_<part>, parts on the knee bones shin_<part>. Pairs whose boxes overlap at rest touch on purpose and go into Ignored.
Writes C# lines to paste into TitanDimsLight.cs."""
import os
import sys

os.environ["LIGHT_NO_MAIN"] = "1"
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import numpy as np  # noqa: E402

import build_light as B  # noqa: E402

OUTF = sys.argv[sys.argv.index("--") + 1:][2]
BONE = {"J_Pelvis": "Pelvis", "J_Waist": "Waist", "J_Torso": "Torso", "J_Hip_L": "HipL", "J_Knee_L": "KneeL", "J_Ankle_L": "AnkleL",
        "J_Hip_R": "HipR", "J_Knee_R": "KneeR", "J_Ankle_R": "AnkleR", "J_Shoulder_L": "ShoulderL", "J_Elbow_L": "ElbowL", "J_Wrist_L": "WristL",
        "J_Shoulder_R": "ShoulderR", "J_Elbow_R": "ElbowR"}
SHRINK = 0.0     # not shrunk: TitanSkeleton.Lowest grounds clip poses with these boxes, a shrink would sink them


def bone_of(joint):
    j = joint
    while j not in BONE:
        j = B.PARENT[j]
    return j


def main():
    objs, meshes, mats = B.build()
    B.set_pose(objs, {})
    boxes = []
    for name, ob in sorted(meshes.items()):
        j = ob["owner_joint"]
        bj = bone_of(j)
        W = B.wverts(ob)                                   # Blender world, zero pose
        A = (B.C.T @ W.T).T                                # analysis
        lo, hi = A.min(0), A.max(0)
        c = (lo + hi) / 2 - B.POS[bj]
        h = np.maximum((hi - lo) / 2 - SHRINK, 0.01)
        bn = BONE[bj]
        pname = ("foot_" + name) if bn.startswith("Ankle") else ("shin_" + name) if bn.startswith("Knee") else name
        boxes.append((pname, bn, c, h, lo, hi))
    ign = []
    for i in range(len(boxes)):
        for k in range(i + 1, len(boxes)):
            a, b = boxes[i], boxes[k]
            if np.all(a[4] < b[5]) and np.all(b[4] < a[5]):
                ign.append((a[0], b[0]))
    lines = ["// generated by model/v3/L/light_part_boxes.py from %s (%d parts, %d pairs touching at rest)" % (B.CODE, len(boxes), len(ign))]
    lines.append("static readonly TitanSkeleton.Part[] Parts =\n{")
    for n, bone, c, h, lo, hi in boxes:
        lines.append('    new TitanSkeleton.Part("%s", TitanBone.%s, V(%.3ff, %.3ff, %.3ff), V(%.3ff, %.3ff, %.3ff)),' % (n, bone, c[0], c[1], c[2], h[0], h[1], h[2]))
    lines.append("};")
    lines.append("static readonly string[] Touching =\n{")
    for a, b in ign:
        lines.append('    "%s|%s",' % (a, b))
    lines.append("};")
    open(OUTF, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    print("=== BOXES", len(boxes), "touching", len(ign))


main()
