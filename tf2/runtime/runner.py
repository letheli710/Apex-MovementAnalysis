"""T5 runner: generate the experiment plan, install HSD.TF2Diag, launch a local
Northstar game, wait for it to quit, and copy the HSDDIAG lines out of the log.

Usage: python -I runner.py <plan name> [--map mp_lf_stacks] [--timeout 600]
  plan name: a function in plans.py returning a list of steps (see plans.py).
Writes runtime/data/<timestamp>_<plan>/{raw.log, diag.tsv, meta.json}.

Only touches: R2Northstar/mods/HSD.TF2Diag (our mod) and reads R2Northstar/logs.

R5 comes first (r5_guard.py): the runner does not start while an R5 measurement is
active (it waits up to --r5-wait minutes, then gives up), and if one starts during a
TF2 run it kills our own game at once and marks the run aborted_r5. The listen server
uses UDP 37115 so it never holds 37015, which R5's hsd_launch.ps1 needs free.
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
import time
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import plans  # noqa: E402
from r5_guard import lock_owner, r5_activity, release_lock, take_lock  # noqa: E402

GAME = Path(r"C:\SteamLibrary\steamapps\common\Titanfall2")
MOD_SRC = HERE.parent / "mod" / "HSD.TF2Diag"
MOD_DST = GAME / "R2Northstar" / "mods" / "HSD.TF2Diag"
LOGS = GAME / "R2Northstar" / "logs"


def squirrel_plan(steps):
    """steps: list of ("cmd", "console command") | ("wait", seconds) | ("until", cond, arg, timeout).
    The plan runs as a client thread (hsd_diag_cl.gnut): waits are client game time, and
    HsdDiag_C (hsd_diag_drv.gnut) logs each command and hands it to the UI console."""
    out = ["// generated by runtime/runner.py; do not edit", "global function HsdDiag_RunPlan", "",
           "void function HsdDiag_RunPlan()", "{"]
    for step in steps:
        kind = step[0]
        if kind == "cmd":
            out.append('\tHsdDiag_C( "%s" )' % step[1].replace('"', '\\"'))
        elif kind == "wait":
            out.append("\twait %s" % repr(float(step[1])))
        elif kind == "until":
            out.append('\tHsdDiag_U( "%s", %s, %s )' % (step[1], repr(float(step[2])), repr(float(step[3]))))
        else:
            raise ValueError(kind)
    out += ["}", ""]
    return "\n".join(out)


def install(steps):
    if MOD_DST.exists():
        shutil.rmtree(MOD_DST)
    shutil.copytree(MOD_SRC, MOD_DST)
    plan_file = MOD_DST / "mod" / "scripts" / "vscripts" / "hsd_diag_plan.gnut"
    plan_file.write_text(squirrel_plan(steps), encoding="utf-8")
    return plan_file.read_text(encoding="utf-8")


def set_mod_defaults(autorun, game_map="mp_lf_stacks"):
    """Write the hsd_autorun / hsd_map defaults into the installed mod.json. A Steam launch
    neither passes long argument lists nor reads ns_startup_args.txt, so this is how a run
    switches the mod on; it is switched off again after every run (manual play stays clean)."""
    mj = MOD_DST / "mod.json"
    if not mj.exists():
        return
    data = json.loads(mj.read_text(encoding="utf-8"))
    for cv in data.get("ConVars", []):
        if cv["Name"] == "hsd_autorun":
            cv["DefaultValue"] = "1" if autorun else "0"
        elif cv["Name"] == "hsd_map":
            cv["DefaultValue"] = game_map
    mj.write_text(json.dumps(data, indent="\t") + "\n", encoding="utf-8")


def newest_log(after):
    if not LOGS.exists():
        return None
    logs = [p for p in LOGS.glob("nslog*.txt") if p.stat().st_mtime >= after]
    return max(logs, key=lambda p: p.stat().st_mtime) if logs else None


PORT = 37115
GUARD_POLL_S = 3.0


def wait_for_tf2_idle(limit_min):
    """Another TF2 runner (another session using this same tool) may hold the lock or have its
    game open; installing the mod or taking the lock then would break its run. Wait for it."""
    deadline = time.time() + limit_min * 60
    while lock_owner() == "tf2" or game_pids():
        print("another TF2 run is active (lock or game); waiting", flush=True)
        if time.time() >= deadline:
            return False
        time.sleep(30)
    return True


def wait_for_r5_idle(limit_min):
    deadline = time.time() + limit_min * 60
    while True:
        reasons = r5_activity()
        if not reasons:
            return True
        print("R5 measurement active, TF2 waits: " + "; ".join(reasons[:3]), flush=True)
        if time.time() >= deadline:
            return False
        time.sleep(30)


# -nojoy (passed on the Steam command line below): skip game-controller init. On
# 2026-10-28 a TF2 launch bugchecked the machine (0x3B in vjoy.sys 2.1.9 while the game
# enumerated input devices); runs need no pad.
STEAM = Path(r"C:\SteamLibrary\steam.exe")
APPID = "1237970"
GAME_IMAGES = ("titanfall2.exe", "northstarlauncher.exe")


def game_pids():
    out = subprocess.run(["tasklist", "/fo", "csv", "/nh"], capture_output=True, text=True).stdout
    pids = []
    for line in out.splitlines():
        cols = [c.strip('"') for c in line.split('","')]
        if len(cols) > 1 and cols[0].strip('"').lower() in GAME_IMAGES:
            pids.append(int(cols[1]))
    return pids


def kill_game(pids):
    for pid in pids:
        subprocess.run(["taskkill", "/PID", str(pid), "/T", "/F"], capture_output=True)


def run_guarded(timeout, start_wait=180):
    """Wait for the Steam-launched game to appear and exit; kill only it if R5 becomes active.
    Returns 'exited', 'timeout', 'no_game' or 'aborted_r5'."""
    end = time.time() + timeout
    appear_by = time.time() + start_wait
    seen = False
    while time.time() < end:
        pids = game_pids()
        if pids:
            seen = True
        elif seen:
            return "exited"
        elif time.time() > appear_by:
            return "no_game"
        reasons = r5_activity()
        if reasons:
            kill_game(pids)
            print("R5 started; TF2 game killed: " + "; ".join(reasons[:3]), flush=True)
            return "aborted_r5"
        time.sleep(GUARD_POLL_S)
    return "timeout"


def acquire(a):
    """Wait until both sides are idle, then take the lock atomically. If another runner took
    it first (both were waiting, 2026-10-29 W1), wait again; after taking it, check once more
    that no game or R5 run slipped in, else give it back and wait. Exits like before (4 / 2)."""
    deadline = time.time() + a.r5_wait * 60
    while True:
        left = max(0.0, (deadline - time.time()) / 60)
        if not a.attach and not wait_for_tf2_idle(left):
            print("another TF2 run still active after %g min; not started" % a.r5_wait)
            sys.exit(4)
        if not wait_for_r5_idle(left):
            print("R5 still active after %g min; TF2 run not started" % a.r5_wait)
            sys.exit(2)
        if take_lock("TF2-Research"):
            if (a.attach or not game_pids()) and not r5_activity():
                return
            release_lock()
            print("game or R5 started while taking the lock; lock released, waiting", flush=True)
        else:
            print("lock taken by another run first (%s); waiting" % lock_owner(), flush=True)
        if time.time() >= deadline:
            print("could not take the lock within %g min; not started" % a.r5_wait)
            sys.exit(4)
        time.sleep(5 + (os.getpid() % 7))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("plan")
    ap.add_argument("--map", default="mp_lf_stacks")
    ap.add_argument("--timeout", type=float, default=600)
    ap.add_argument("--r5-wait", type=float, default=60, help="minutes to wait for R5 to go idle")
    ap.add_argument("--mouse", action="store_true",
                    help="titan T0: send scripted mouse moves on hsd_mouse plan lines (expansion/titan/titan_mouse.py)")
    ap.add_argument("--attach", action="store_true",
                    help="guard and collect an already running game (installed plan) instead of launching one")
    a = ap.parse_args()
    acquire(a)
    try:
        run(a)
    finally:
        release_lock()


def run(a):
    if a.attach:
        t0 = time.time()
        out = HERE / "data" / (datetime.now().strftime("%Y%m%d_%H%M%S") + "_" + a.plan + "_attach")
        out.mkdir(parents=True)
        outcome = run_guarded(a.timeout, start_wait=5)
        collect(out, {"plan": a.plan, "attach": True, "start": t0, "end": time.time(), "outcome": outcome},
                newest_log(0))
        return
    steps = getattr(plans, a.plan)()
    plan_text = install(steps)
    out = HERE / "data" / (datetime.now().strftime("%Y%m%d_%H%M%S") + "_" + a.plan)
    out.mkdir(parents=True)
    (out / "plan.gnut").write_text(plan_text, encoding="utf-8")

    if game_pids():
        print("a Titanfall 2 game is already running; close it first")
        sys.exit(3)
    t0 = time.time()
    # Launched through Steam with -northstar (Northstar's documented way): running
    # NorthstarLauncher.exe directly fails EA ownership auth (UNAUTHORIZED_GAME) for the
    # Steam copy. That launch drops the tail of long argument lists and does not read
    # ns_startup_args.txt, so: only -northstar -nojoy on the command line (-nojoy right
    # after -northstar; the log's "Command line" proves it arrived), the mod is switched on
    # through its mod.json defaults for this run, and the UI script sets hostport and the
    # match ConVars before loading the map. No auth bypass flags.
    args = [str(STEAM), "-applaunch", APPID, "-northstar", "-nojoy"]
    set_mod_defaults(True, a.map)
    mouse = None
    if a.mouse:
        sys.path.insert(0, str(HERE.parent / "expansion" / "titan"))
        from titan_mouse import MouseDriver
        mouse = MouseDriver(LOGS, t0, game_pids)
        mouse.start()
    try:
        subprocess.Popen(args)
        outcome = run_guarded(a.timeout)
    finally:
        set_mod_defaults(False)
        if mouse:
            mouse.stop()
            (out / "mouse.json").write_text(json.dumps(mouse.records, indent=1), encoding="utf-8")
    if outcome == "timeout":
        # our own game: close it before the lock is released, or R5 could start next to it
        # (2026-10-29 t1_sky run: kicked by the stringcmd quota, game left running)
        kill_game(game_pids())
        print("timeout; our game was killed")
    meta = {"plan": a.plan, "map": a.map, "args": args, "start": t0, "end": time.time(), "outcome": outcome}
    collect(out, meta, newest_log(t0 - 5))


def collect(out, meta, log):
    meta["log"] = str(log) if log else None
    if log:
        text = log.read_text(encoding="utf-8", errors="replace")
        (out / "raw.log").write_text(text, encoding="utf-8")
        lines = [l[l.index("HSDDIAG"):] for l in text.splitlines() if "HSDDIAG" in l]
        (out / "diag.tsv").write_text("\n".join(lines) + "\n", encoding="utf-8")
        meta["diag_lines"] = len(lines)
        # client frame time: a run must be ~7 ms (144 fps); 50 ms means the window was
        # throttled (not_focus_sleep) and movement was simulated in 50 ms steps
        ts = [float(l.split()[2]) for l in lines if l.startswith("HSDDIAG C ")]
        dts = sorted(b - a for a, b in zip(ts, ts[1:]) if b > a)
        if dts:
            meta["client_dt_median_ms"] = round(dts[len(dts) // 2] * 1000, 2)
            meta["client_dt_p95_ms"] = round(dts[int(len(dts) * 0.95)] * 1000, 2)
    (out / "meta.json").write_text(json.dumps(meta, indent=1), encoding="utf-8")
    print(json.dumps(meta, indent=1))
    print("data:", out)


if __name__ == "__main__":
    main()
