"""Write m4/unity/scenarios.json, the scenario sidecar of the M4 Unity replay (stdlib only).

The input stream of a trial (buttons, axes, view) triggers the abilities. Everything else a replay needs is a scenario fact:
which legend/kit, where the harness put the jump pad / gravity lift, which surface the grapple hits, and two kinds of per-trial
state that the trial itself does not record:

  * grapple_release_step: the recorded detach command. The detach rule is UNKNOWN (LIFT-GRAPPLE-PRIMITIVES §2.5), so the replay
    releases the pull where R5 did: the first step after the pull start whose velocity change is ballistic again (the analysis rule
    `grapple_events`, PULL_TOL 0.05 u/s), cross-checked against ../lift_grapple/results.json.
  * stim_initial_onset_s / stim_ready: two trials started inside the previous trial's stim (OCTANE-PRIMITIVES §1, contamination).
    The onset is placed 6.0 s (stim full duration) before the first faded command of the recorded movescale column; the carried-over
    trial's own tap gave no stim in R5 (r1517), so its tactical is marked not ready.

Harness constants (research/phase2-local/tools/hsd_trial.py, test_geometry.py) are quoted where they are used. Nothing is fitted.

    python make_scenarios.py
"""
import csv
import json
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))
TRIALS = os.path.join(HERE, "..", "trials")
LG_RESULTS = os.path.join(HERE, "..", "lift_grapple", "results.json")
G = 750.0
PULL_TOL = 0.05
IN_OFFHAND1 = 0x200000
STIM_PLATEAU = 1.4927        # movescale at full stim strength (1.15 * 1.298038, printed to 4 decimals)
STIM_FULL = 6.0              # octane params stim.full_duration (script value)

# reset origins (hsd_trial.py): lane A (-14100, 6500, 294.92), lane C (-14800, 6800, 294.92)
LANE_C = (-14800.0, 6800.0, 294.92)
PAD = [LANE_C[0] + 300.0, LANE_C[1], LANE_C[2]]      # SCHEDULE_PRE m4_pad_: JumpPad_CreateAtLocation(o + <300, 0, 0>)
LIFT = [LANE_C[0] + 120.0, LANE_C[1], LANE_C[2]]     # SCHEDULE_PRE m4_lift_: SpaceElevator_PropDeploy(o + <120, 0, 0>)
WALL = {"point": [-13706.0, 6500.0, 294.92], "normal": [-1.0, 0.0, 0.0],
        "source": "test_geometry.py M3 test wall: face x ~ -13706 (normal -X), y 6380..6620; lift_grapple_analysis.py WALL_X -13706",
        # F3 feel comparison: the same wall as a solid box for a game body's world (its grapple hits the world). Face, width and the
        # 232 u height from test_geometry.py; the 200 u depth is a stand-in (the rock is deeper, only the face is ever reached)
        "box": {"min": [-13706.0, 6380.0, 294.92], "max": [-13506.0, 6620.0, 526.92]}}


def read(trial):
    with open(os.path.join(TRIALS, trial, "samples.csv"), newline="") as fh:
        rows = list(csv.DictReader(fh))
    for r in rows:
        for k in ("t", "dt", "vel_x", "vel_y", "vel_z", "movescale", "cmd_fwd", "cmd_side"):
            r[k] = float(r[k])
        r["buttons"] = int(r["buttons"] or 0)
        r["grounded"] = int(r["grounded"] or 0)
        r["step"] = int(r["step"])
    return rows


def grapple_release(rows):
    """First step after the pull whose velocity change is ballistic again (no input), analysis rule on the frame states."""
    fire = next(i for i, r in enumerate(rows) if r["buttons"] & IN_OFFHAND1)

    def dev(i):
        a, b = rows[i - 1], rows[i]
        return max(abs(b["vel_x"] - a["vel_x"]), abs(b["vel_y"] - a["vel_y"]), abs(b["vel_z"] - (a["vel_z"] - G * b["dt"])))

    hop = next(i for i in range(fire + 1, len(rows)) if abs(rows[i]["vel_z"] - rows[i - 1]["vel_z"]) > 20)
    pull = next(i for i in range(hop + 1, len(rows)) if not rows[i]["grounded"] and dev(i) > PULL_TOL)
    end = next(i for i in range(pull + 1, len(rows)) if dev(i) <= PULL_TOL or rows[i]["grounded"]
               or rows[i]["vel_x"] - rows[i - 1]["vel_x"] < -50)
    return fire, hop, pull, end


def stim_carry_over(rows):
    """Onset time (s since the trial start) of a stim already running at step 0, or None."""
    if abs(rows[0]["movescale"] - STIM_PLATEAU) > 1e-4:
        return None
    fade = next(i for i, r in enumerate(rows) if r["movescale"] < STIM_PLATEAU - 1e-4)
    start = sum(r["dt"] for r in rows[:fade])          # start time of the first faded step
    return start - STIM_FULL, fade


def main():
    lg = json.load(open(LG_RESULTS, encoding="utf-8"))
    lg_hold = {("r%d" % t["run"]): t["events"] for t in lg["grapple"]["trials"]}
    lg_series = {("r%d" % t["run"]): t for t in lg["grapple_series"]["trials"]}

    out = {
        "format": "hsd-m4-scenarios/1",
        "description": "Scenario facts of the M4 replay trials that the input stream does not carry. Generated by make_scenarios.py; "
                       "harness constants from research/phase2-local/tools/hsd_trial.py, per-trial state from the reference trial "
                       "(recorded events, not fitted values).",
        "motor": {"lurchClampSprintFraction": 0.7,
                  "source": "octane/params.json lurch.clamp: 0.7 x current sprint cap (294.67 under stim, 209.3 without)"},
        "kits": {
            "octane": ["landing_slowdown", "stim", "jump_pad"],
            "horizon": ["landing_slowdown", "air_profile", "gravity_lift"],
            "pathfinder": ["landing_slowdown", "grapple"],
            "valkyrie": ["landing_slowdown", "jets"],
            "revenant": ["landing_slowdown", "pounce"],
        },
        "schedules": {},
        "trials": {},
    }
    S = out["schedules"]
    for s in ("m4_ctrl_sprint", "m4_ctrl_air", "m4_stim_sprint", "m4_stim_walk", "m4_stim_air"):
        S[s] = {"legend": "octane"}
    for s in ("m4_pad_sprint", "m4_pad_walk", "m4_pad_crouch"):
        S[s] = {"legend": "octane", "jump_pad": PAD,
                "jump_pad_source": "hsd_trial.py SCHEDULE_PRE m4_pad_: JumpPad_CreateAtLocation(o + <300,0,0>) at reset, o = lane C (-14800, 6800, 294.92)"}
    for s in ("e2_noinput", "e4_stand"):
        S[s] = {"legend": "horizon"}
    for s in ("m4_lift_ride", "m4_lift_jumpout", "m4_lift_strafe"):
        S[s] = {"legend": "horizon", "gravity_lift": {
            "base": LIFT, "deploy_time_s": 0.0,
            "source": "hsd_trial.py SCHEDULE_PRE m4_lift_: SpaceElevator_PropDeploy(o + <120,0,0>) at reset (centre fitted -14680.02, 6800.00 in "
                      "lift_grapple §1.1; deployed before step 0, deploy_time 0 is a lower bound: the 10 s lifetime never ends a ride here)"}}
    for s in ("m4_grapple_hold", "m4_grapple_near"):
        S[s] = {"legend": "pathfinder", "grapple_surface": WALL}
    for s in ("m4_valk_ctrl", "m4_valk_jets"):
        S[s] = {"legend": "valkyrie"}
    for s in ("m4_pounce_c0", "m4_pounce_c13"):
        S[s] = {"legend": "revenant"}

    checks = []
    for d in sorted(os.listdir(TRIALS)):
        if d.endswith("_REJECTED") or not os.path.isdir(os.path.join(TRIALS, d)):
            continue
        tid = json.load(open(os.path.join(TRIALS, d, "trial.json"), encoding="utf-8"))["trial_id"]
        sched, run = d.rsplit("_", 1)
        if sched not in S:
            raise SystemExit("no schedule entry for " + d)
        rows = read(d)
        if sched.startswith("m4_grapple"):
            fire, hop, pull, end = grapple_release(rows)
            src = f"reference: fire step {fire}, hop {hop}, pull {pull}..{end - 1}, first ballistic step {end} (analysis rule grapple_events)"
            if run in lg_hold:
                e = lg_hold[run]
                ok = (e["fire"] + 1, e["hop"] + 1, e["pull"] + 1, e["pull_end"] + 1) == (fire, hop, pull, end)
                src += f"; lift_grapple/results.json grapple cmd index +1 = ({e['fire'] + 1}, {e['hop'] + 1}, {e['pull'] + 1}, {e['pull_end'] + 1}): {'match' if ok else 'MISMATCH'}"
                checks.append((d, ok))
            elif run in lg_series:
                e = lg_series[run]
                t_fire = sum(r["dt"] for r in rows[:fire])
                t_end = sum(r["dt"] for r in rows[:end])
                dur = t_end - t_fire - e["t_pull"]
                ok = abs(dur - e["t_pull_dur"]) < 0.0125
                src += f"; lift_grapple/results.json grapple_series t_pull + t_pull_dur = {e['t_pull'] + e['t_pull_dur']:.4f} s vs {t_end - t_fire:.4f} s here: {'match' if ok else 'MISMATCH'}"
                checks.append((d, ok))
            out["trials"][tid] = {"grapple_release_step": end, "source": src}
        co = stim_carry_over(rows)
        if co is not None:
            onset, fade = co
            entry = {"stim_initial_onset_s": round(onset, 5),
                     "source": f"stim carried over from the previous trial: msc {rows[0]['movescale']} at step 0, first faded step {fade}; onset = its start - 6.0 s (octane §1 contamination)"}
            if any(r["buttons"] & IN_OFFHAND1 for r in rows):
                entry["stim_ready"] = 0
                entry["source"] += "; the trial's own tap gave no new stim in R5 (octane §1: r1517/r1519), tactical not ready"
            out["trials"][tid] = entry
    with open(os.path.join(HERE, "scenarios.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, indent=1)
        fh.write("\n")
    for d, ok in checks:
        print(f"{d:28s} release cross-check {'ok' if ok else 'MISMATCH'}")
    print("wrote scenarios.json:", len(out["schedules"]), "schedules,", len(out["trials"]), "trial entries")
    return 0 if all(ok for _, ok in checks) else 1


if __name__ == "__main__":
    raise SystemExit(main())
