"""Synthetic log generator for tests and dry runs.

THE OUTPUT IS NOT APEX DATA. It is produced by a deliberately simple model
("SYNTH-1") with known parameters so tests can check that the parser,
validators, event detection and fitters recover what was put in. Every file
starts with a "# SYNTHETIC" header line.

Line formats mirror the real producers:
  [MOVE-TRACE]  s21-r5sdk/src/game/{client,server}/move_sim_trace.cpp printf
  [HSD-MD] ver=2 research/phase1/mod/hsd_movediag (v0.2)
  file prefix   "[YYYY-MM-DD HH:MM:SS.mmm] Native(C): " / "Script(S): " (core/logdef.cpp, public/tier0/dbg.h)
"""
import math
import os
import random
import re

HEADER = "# SYNTHETIC TEST DATA generated by hsdtel.synth (model SYNTH-1) -- NOT APEX MEASUREMENTS\n"

# SYNTH-1 parameters (made up; chosen so every fitter has something to find)
P = {
    "fps": 144.0,
    "wish_ground": 300.0,      # ground target speed
    "ground_accel": 1800.0,    # linear, u/s^2
    "friction_k": 5.0,         # Source-style friction, 1/s
    "stopspeed": 100.0,
    "air_cap": 40.0,           # flat AirAccelerate: wish speed cap
    "air_accel": 2400.0,       # flat AirAccelerate: accelspeed = accel * dt
    "gravity": 750.0,
    "jump_vz": math.sqrt(2 * 750.0 * 56.0),
    "slide_decel": 150.0,
}

IN_JUMP, IN_DUCK, IN_FORWARD, IN_MOVERIGHT = 1 << 1, 1 << 2, 1 << 3, 1 << 10


def _read(path):
    with open(path) as fh:
        return fh.read()


def _write(path, text, lines=False):
    with open(path, "w", newline="\n") as fh:
        if lines:
            fh.writelines(text)
        else:
            fh.write(text)


def _stamp(base_wall, t):
    ms_total = int(round((base_wall + t) * 1000))
    s, ms = divmod(ms_total, 1000)
    hh, rem = divmod(s % 86400, 3600)
    mi, ss = divmod(rem, 60)
    return f"[2026-10-21 {hh:02d}:{mi:02d}:{ss:02d}.{ms:03d}] "


class Sim:
    def __init__(self, seed=1):
        self.rng = random.Random(seed)
        self.ft = 1.0 / P["fps"]
        self.t = 100.0          # script Time() at start
        self.cmd = 5000
        self.o = [0.0, 0.0, 0.0]
        self.v = [0.0, 0.0, 0.0]
        self.ground = 1
        self.slide = 0
        self.prev_buttons = 0
        self.records = []       # one dict per command

    def step(self, ax_fwd, ax_right, yaw, jump=False, duck=False, run=0):
        ft = self.ft
        pre_o, pre_v, pre_ground, pre_slide = list(self.o), list(self.v), self.ground, self.slide
        buttons = (IN_FORWARD if ax_fwd > 0 else 0) | (IN_MOVERIGHT if ax_right > 0 else 0) \
            | (IN_JUMP if jump else 0) | (IN_DUCK if duck else 0)
        pressed = buttons & ~self.prev_buttons
        wish_mag = min(1.0, math.hypot(ax_fwd, ax_right))
        wish_yaw = yaw + math.degrees(math.atan2(-ax_right, ax_fwd)) if wish_mag > 0 else None
        vx, vy, vz = self.v
        jumped = False
        if self.ground:
            if pressed & IN_JUMP:
                vz = P["jump_vz"]
                self.ground = 0
                jumped = True       # friction skipped on the jump command
            elif self.slide:
                spd = math.hypot(vx, vy)
                ns = max(0.0, spd - P["slide_decel"] * ft)
                if spd > 0:
                    vx, vy = vx * ns / spd, vy * ns / spd
                if ns < 50 or not duck:
                    self.slide = 0
            elif wish_yaw is not None:
                wx, wy = math.cos(math.radians(wish_yaw)), math.sin(math.radians(wish_yaw))
                spd = math.hypot(vx, vy)
                target = P["wish_ground"] * wish_mag
                ns = min(target, spd + P["ground_accel"] * ft) if spd < target else spd
                vx, vy = wx * ns, wy * ns
            else:
                spd = math.hypot(vx, vy)
                if spd > 0:
                    ns = max(0.0, spd - max(spd, P["stopspeed"]) * P["friction_k"] * ft)
                    vx, vy = vx * ns / spd, vy * ns / spd
            if duck and not self.slide and math.hypot(vx, vy) > 250 and not jumped:
                self.slide = 1
        if not self.ground and not jumped:
            if wish_yaw is not None:
                wx, wy = math.cos(math.radians(wish_yaw)), math.sin(math.radians(wish_yaw))
                wishspeed = min(P["wish_ground"] * wish_mag, P["air_cap"])
                add = wishspeed - (vx * wx + vy * wy)
                if add > 0:
                    acc = min(P["air_accel"] * ft, add)
                    vx, vy = vx + acc * wx, vy + acc * wy
            vz -= P["gravity"] * ft
        ox, oy, oz = self.o[0] + vx * ft, self.o[1] + vy * ft, self.o[2] + vz * ft
        if not self.ground and oz <= 0.0 and vz <= 0.0:
            oz, vz = 0.0, 0.0
            self.ground = 1
        self.o, self.v = [ox, oy, oz], [vx, vy, vz]
        self.t += ft
        self.cmd += 1
        self.prev_buttons = buttons
        self.records.append(dict(
            cmd=self.cmd, t=self.t, run=run, pre_o=pre_o, pre_v=pre_v, post_o=list(self.o), post_v=list(self.v),
            pre_ground=pre_ground, post_ground=self.ground, pre_slide=pre_slide, post_slide=self.slide,
            buttons=buttons, ax_fwd=ax_fwd, ax_right=ax_right, yaw=yaw, jumped=jumped,
            in_jump=1 if jump else 0, in_duck=1 if duck else 0, in_fwd=1 if ax_fwd > 0 else 0))

    def hold(self, seconds, **kw):
        for _ in range(int(round(seconds / self.ft))):
            self.step(**kw)


def scenario(sim):
    # run 1 -- E1: rest, accelerate forward, release and coast
    sim.hold(0.3, ax_fwd=0, ax_right=0, yaw=0, run=1)
    sim.hold(2.0, ax_fwd=1, ax_right=0, yaw=0, run=1)
    sim.hold(2.0, ax_fwd=0, ax_right=0, yaw=0, run=1)
    # run 2 -- E2: run up, jump, air strafe while turning right at 180 deg/s, three jumps
    sim.hold(1.0, ax_fwd=1, ax_right=0, yaw=0, run=2)
    yaw = 0.0
    for _ in range(3):
        sim.step(ax_fwd=1, ax_right=0, yaw=yaw, jump=True, run=2)
        while not sim.ground:
            yaw -= 180.0 * sim.ft
            sim.step(ax_fwd=0, ax_right=1, yaw=yaw, run=2)
        sim.step(ax_fwd=1, ax_right=0, yaw=yaw, run=2)
    sim.hold(1.0, ax_fwd=0, ax_right=0, yaw=yaw, run=2)
    # run 3 -- E4/E5: bunny hops with 0/2/5 extra ground frames, then a slide
    sim.hold(1.0, ax_fwd=1, ax_right=0, yaw=0, run=3)
    for wait in (0, 2, 5):
        sim.step(ax_fwd=1, ax_right=0, yaw=0, jump=True, run=3)
        while not sim.ground:
            sim.step(ax_fwd=1, ax_right=0, yaw=0, run=3)
        for _ in range(wait):
            sim.step(ax_fwd=1, ax_right=0, yaw=0, run=3)
    sim.hold(0.5, ax_fwd=1, ax_right=0, yaw=0, run=3)
    sim.hold(0.8, ax_fwd=1, ax_right=0, yaw=0, duck=True, run=3)
    sim.hold(1.0, ax_fwd=0, ax_right=0, yaw=0, run=3)


def _mt(r, noise=0.0, rng=None, replay=False):
    def n(x):
        return x + (rng.uniform(-noise, noise) if noise else 0.0)
    o, v, po, pv = r["pre_o"], r["pre_v"], r["post_o"], r["post_v"]
    line = ("[MOVE-TRACE] cmd=%d ent=1 ms=%.3f spr=%d duck=%d slide=%d ge=%d fwd=%.3f sd=%.3f b=%08X msc=%.4f "
            "o=%.3f %.3f %.3f v=%.3f %.3f %.3f po=%.3f %.3f %.3f pv=%.3f %.3f %.3f%s") % (
        r["cmd"], P["wish_ground"], 0, 2 if r["in_duck"] else 0, r["pre_slide"], r["pre_ground"],
        r["ax_fwd"], r["ax_right"], r["buttons"], 1.0,
        n(o[0]), n(o[1]), n(o[2]), n(v[0]), n(v[1]), n(v[2]), n(po[0]), n(po[1]), n(po[2]),
        n(pv[0]), n(pv[1]), n(pv[2]), " rp=1" if replay else "")
    return line


def _state(o, v, ground, slide, crouch):
    return ("o=%.3f,%.3f,%.3f vel=%.3f,%.3f,%.3f spd2d=%.3f vz=%.3f ground=%d slide=%d sprint=0 crouch=%d"
            % (o[0], o[1], o[2], v[0], v[1], v[2], math.hypot(v[0], v[1]), v[2], ground, slide, crouch))


def write_logs(out_dir, seed=1, base_wall=36000.0):
    """Writes client/ and server/ SDK-style log folders. Returns the file paths."""
    sim = Sim(seed)
    scenario(sim)
    rng = random.Random(seed + 1)
    t0 = sim.records[0]["t"] - sim.ft
    cl_dir = os.path.join(out_dir, "platform", "logs", "client", "00000000-synth-client")
    sv_dir = os.path.join(out_dir, "platform", "logs", "server", "00000000-synth-server")
    os.makedirs(cl_dir, exist_ok=True)
    os.makedirs(sv_dir, exist_ok=True)
    cl_msg, cl_scr = [HEADER], [HEADER]
    sv_msg, sv_scr = [HEADER], [HEADER]
    seq = {"cl": 0, "sv": 0}

    def head(side, kind, run):
        seq[side] += 1
        return f"[HSD-MD] ver=2 side={side} kind={kind} run={run} seq={seq[side]}"

    cl_scr.append(_stamp(base_wall, 0) + "Script(C): " + head("cl", "init", 0) + " mod=0.2.0\n")
    sv_scr.append(_stamp(base_wall, 0) + "Script(S): " + head("sv", "init", 0) + " mod=0.2.0\n")
    # E0 census inputs: client bridge_classvar_get output (message.log) and both mod dumps.
    for key, val, typ in (("airAcceleration", "2400", 2), ("airSpeed", "40", 2), ("doubleJump", "false", 0)):
        cl_msg.append(_stamp(base_wall, 0.0) + f"Native(C): [CLASSVAR] {key} = {val} (type={typ} off=1234)\n")
    cl_msg.append(_stamp(base_wall, 0.0) + "Native(C): [CLASSVAR] unknown key 'dodgeSpeed'\n")
    for key, val in (("airAcceleration", "2400.000000"), ("airSpeed", "45.000000")):
        cl_scr.append(_stamp(base_wall, 0.0) + "Script(C): " + head("cl", "setting", 0)
                      + f" ent=1 key={key} vtype=float value={val}\n")
    for side, lines, pref in (("sv", sv_scr, "Script(S): "),):
        for key, val, vtype in (("airAcceleration", "2400.000000", "float"), ("airSpeed", "40.000000", "float"),
                                ("doubleJump", "0", "int"), ("dodgeSpeed", "", "ERR")):
            lines.append(_stamp(base_wall, 0.0) + pref + head(side, "setting", 0)
                         + f" ent=1 key={key} vtype={vtype} value={val or '-'}\n")
        lines.append(_stamp(base_wall, 0.0) + pref + head(side, "dump", 0) + " ent=1 ok=3 total=4\n")

    cur_run = 0
    takeoff = None
    ground_start = None
    for i, r in enumerate(sim.records):
        rel = r["t"] - t0
        if r["run"] != cur_run:
            for side, lines, pref in (("cl", cl_scr, "Script(C): "), ("sv", sv_scr, "Script(S): ")):
                seq_line = head(side, "run", r["run"]) + f" prev={cur_run} t={r['t']:.4f}"
                lines.append(_stamp(base_wall, rel - 0.0005) + pref + seq_line + "\n")
            cur_run = r["run"]
        # client: prediction log, then the script sample of the same frame
        cl_msg.append(_stamp(base_wall, rel) + "Native(C): " + _mt(r) + "\n")
        if i % 50 == 49:
            cl_msg.append(_stamp(base_wall, rel) + "Native(C): " + _mt(r, 0.001, rng, replay=True) + "\n")
        po, pv = r["post_o"], r["post_v"]
        st = _state(po, pv, r["post_ground"], r["post_slide"], r["in_duck"])
        cl_scr.append(_stamp(base_wall, rel + 0.0002) + "Script(C): " + head("cl", "frame", r["run"])
                      + f" t={r['t']:.4f} ft={sim.ft:.5f} {st} ang=0.000,{r['yaw']:.3f} in_jump={r['in_jump']}"
                      f" in_duck={r['in_duck']} in_fwd={r['in_fwd']} ax_fwd={r['ax_fwd']:.3f} ax_right={r['ax_right']:.3f}\n")
        if r["pre_ground"] == 1 and r["post_ground"] == 0:
            gt = r["t"] - ground_start if ground_start is not None else 0.0
            takeoff = (r["t"], math.hypot(pv[0], pv[1]), 0.0)
            cl_scr.append(_stamp(base_wall, rel + 0.0003) + "Script(C): " + head("cl", "takeoff", r["run"])
                          + f" t={r['t']:.4f} groundtime={gt:.4f} hop=0 {st}\n")
        if takeoff and r["post_ground"] == 0:
            takeoff = (takeoff[0], takeoff[1], max(takeoff[2], math.hypot(pv[0], pv[1])))
        if r["pre_ground"] == 0 and r["post_ground"] == 1 and takeoff:
            spd = math.hypot(pv[0], pv[1])
            cl_scr.append(_stamp(base_wall, rel + 0.0003) + "Script(C): " + head("cl", "land", r["run"])
                          + f" t={r['t']:.4f} airtime={r['t'] - takeoff[0]:.4f} takeoff={takeoff[1]:.3f}"
                          f" peak={takeoff[2]:.3f} land={spd:.3f} gain={spd - takeoff[1]:.3f} hop=0 {st}\n")
            ground_start = r["t"]
        if r["pre_ground"] == 1 and ground_start is None:
            ground_start = r["t"]
        # server: same command, run in 50 ms batches (wall clock of the batch end)
        batch_rel = math.ceil(rel / 0.05) * 0.05 + 0.004
        sv_msg.append(_stamp(base_wall, batch_rel) + "Native(S): " + _mt(r, 0.0005, rng) + "\n")
        evts = []
        if r["jumped"]:
            evts += ["JUMP", "LEAVE_GROUND"]
        if r["pre_ground"] == 0 and r["post_ground"] == 1:
            evts.append("TOUCH_GROUND")
        if r["pre_slide"] == 0 and r["post_slide"] == 1:
            evts.append("BEGIN_SLIDE")
        if r["pre_slide"] == 1 and r["post_slide"] == 0:
            evts.append("END_SLIDE")
        for e in evts:
            sv_scr.append(_stamp(base_wall, batch_rel + 0.0001) + "Script(S): " + head("sv", "evt", r["run"])
                          + f" evt={e} t={r['t']:.4f} ent=1 bot=0 {st}\n")
    paths = {}
    for name, d, lines in (("cl_message", cl_dir, cl_msg), ("cl_script", cl_dir, cl_scr),
                           ("sv_message", sv_dir, sv_msg), ("sv_script", sv_dir, sv_scr)):
        fn = os.path.join(d, ("message.log" if "message" in name else "script.log"))
        with open(fn, "w", newline="\n") as fh:
            fh.writelines(lines)
        paths[name] = fn
    return paths, sim


def write_faulty(src_paths, out_dir):
    """Copies the client logs with one injected defect of each kind. Returns
    {path: [expected issue codes]}."""
    os.makedirs(out_dir, exist_ok=True)
    msg = _read(src_paths["cl_message"]).split("\n")
    scr = _read(src_paths["cl_script"]).split("\n")
    mt_idx = [i for i, l in enumerate(msg) if "[MOVE-TRACE]" in l and "rp=1" not in l]
    msg[mt_idx[10]] = msg[mt_idx[10]][:msg[mt_idx[10]].index(" po=")]          # truncated line
    msg[mt_idx[20]] = re.sub(r" v=\S+ ", " v=-nan(ind) ", msg[mt_idx[20]], count=1)          # MSVC NaN
    msg[mt_idx[30]] = re.sub(r" o=\S+ ", " o=9000.000 ", msg[mt_idx[30]], count=1)            # teleport in x
    hsd_idx = [i for i, l in enumerate(scr) if "kind=frame" in l]
    del scr[hsd_idx[40]]                                                           # seq gap
    scr[hsd_idx[60]] = scr[hsd_idx[60]].replace(" ground=", " grnd=", 1)          # missing field
    scr[hsd_idx[80]] = scr[hsd_idx[80]].replace(" ground=1 ", " ground=-1 ").replace(" ground=0 ", " ground=-1 ")
    scr.insert(hsd_idx[90], scr[hsd_idx[90]].split("[HSD-MD]")[0]
               + "[HSD-MD] ver=2 side=cl kind=error run=1 seq=999999 where=sample count=1 msg=the index 'IsSliding' does not exist")
    p_msg = os.path.join(out_dir, "faulty_client_message.log")
    p_scr = os.path.join(out_dir, "faulty_client_script.log")
    _write(p_msg, "\n".join(msg))
    _write(p_scr, "\n".join(scr))
    expected = {"E_MALFORMED_MT", "E_NONFINITE", "W_TELEPORT", "W_SEQ_GAP", "E_MISSING_FIELD",
                "W_API_MISSING", "W_SCRIPT_ERROR"}
    return [p_msg, p_scr], expected


def write_console_copy(src_paths, out_path, n=200):
    """A console-style copy: ANSI colour codes, no file timestamp."""
    lines = [HEADER]
    for l in _read(src_paths["cl_message"]).split("\n")[1:n]:
        if "]" in l:
            body = l.split("] ", 1)[1].replace("Native(C): ", "\x1b[38;2;118;118;118mNative(C): \x1b[38;2;204;204;204m")
            lines.append(body + "\x1b[0m\n")
    _write(out_path, lines, lines=True)
    return out_path
